#pragma once

// Shared linear-light float image support for the Radiance HDR and OpenEXR
// decoders. Both formats carry scene-linear values (often above 1.0), so the
// decoders produce a linear RGBA float image and the one documented policy here
// converts it into the existing closed RGBA8 material-texture contract:
//
//  - Color / Emissive: Reinhard tone map (exposure 1.0, c / (1 + c)) followed by
//    the caller's transfer function. The adapter passes sRGB for base-color and
//    emissive slots.
//  - Data / Normal: no tone curve; values are clamped to [0, 1] and kept linear
//    (the adapter passes Linear). Normal maps therefore keep their authored
//    X/Y/Z encoding instead of being compressed by a display curve.
//  - Alpha is always linear and clamped.
//
// Downscaling to options.maxDimension is area-averaged in linear light before
// the policy is applied, matching the WIC/TGA/DDS progressive-halving path. The
// result is mip-generated by the same shared bounded helper those decoders use.

#include "TextureTranscodeAdapter.h"

#include <algorithm>
#include <cstdint>
#include <optional>
#include <vector>

namespace import_worker {

// Transient float storage is allowed to exceed the RGBA8 output budget (four
// floats per texel versus four bytes) but never without a fixed floor. This
// keeps a 2K EXR inside the default per-texture budget while rejecting a 4K
// float allocation that could not produce a bounded preview anyway.
inline uint64_t LinearFloatTransientLimit(const TextureDecodeOptions& options)
{
    return (std::max)(options.maxDecodedBytes, uint64_t(64) * 1024 * 1024);
}

// Tightly packed, top-left-origin linear RGBA float texels.
struct LinearRgbaImage {
    uint32_t width = 0;
    uint32_t height = 0;
    std::vector<float> rgba;
};

// Applies the documented HDR tone/transfer policy and the shared RGBA8
// finalization. Returns nullopt on cancellation, malformed input, or a budget
// overflow. `image` is consumed.
std::optional<TranscodedImage> FinalizeLinearImage(LinearRgbaImage image,
                                                   model_core::ColorSpaceId colorSpace,
                                                   const TextureDecodeOptions& options);

// Area-downscales a linear RGBA float image to fit maxDimension. Used by the
// environment asset hook, which stays in float rather than tonemapping.
std::optional<LinearRgbaImage> DownscaleLinearRgba(LinearRgbaImage image, uint32_t maxDimension,
                                                   uint64_t maxPixels, const TextureDecodeOptions& options);

} // namespace import_worker
